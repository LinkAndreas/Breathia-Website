// Pulls the technique catalog and its translations from the Breathia app repository into
// content/app.js, so the website shows exactly what the app ships.
//
//   npm run sync                               # app repo at ../../Swift/Breathia
//   BREATHIA_APP=/path/to/Breathia npm run sync

import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const appRepo = path.resolve(process.env.BREATHIA_APP ?? path.join(root, '../../Swift/Breathia'));
// Website language codes, and the app localization each one comes from where it differs.
const languages = ['en', 'de', 'fr', 'es', 'it', 'pt-br', 'nl', 'ja', 'ko', 'zh', 'ru'];
const appLocalization = { 'pt-br': 'pt-BR', zh: 'zh-Hans' };

const catalogSource = await readFile(path.join(appRepo, 'Shared/Domain/Model/TechniqueCatalog.swift'), 'utf8');
const { strings } = JSON.parse(await readFile(path.join(appRepo, 'Shared/Localizable.xcstrings'), 'utf8'));

function localized(key) {
  const entry = strings[key];
  if (!entry) throw new Error(`Missing string "${key}" in Localizable.xcstrings`);
  return Object.fromEntries(
    languages.map((lang) => {
      const value = entry.localizations?.[appLocalization[lang] ?? lang]?.stringUnit?.value;
      if (!value) throw new Error(`Missing ${lang} translation for "${key}"`);
      return [lang, value];
    }),
  );
}

// Technique(id: "…", … category: .x, … recommendedDuration: n, phases: [ … ], … hue: n)
const techniquePattern =
  /Technique\(\s*id: "([^"]+)".*?category: \.(\w+).*?recommendedDuration: (\d+).*?phases: \[(.*?)\],.*?hue: (\d+)/gs;
const phasePattern = /\.(inhale|exhale|hold)\((\d+)(?:,\s*scale:\s*([\d.]+))?\)/g;
const defaultScale = { inhale: 1.15, exhale: 0.8 };

const techniques = [...catalogSource.matchAll(techniquePattern)].map(([, id, category, duration, phases, hue]) => ({
  id,
  category,
  minutes: Number(duration) / 60,
  hue: Number(hue),
  phases: [...phases.matchAll(phasePattern)].map(([, kind, seconds, scale]) => ({
    kind,
    seconds: Number(seconds),
    scale: scale ? Number(scale) : defaultScale[kind],
  })),
  name: localized(`technique.${id}.name`),
  purpose: localized(`technique.${id}.purpose`),
}));

if (techniques.length === 0) throw new Error('No techniques found — has TechniqueCatalog.swift changed shape?');

const categoryKeys = {
  hrv: 'technique.category.hrvCoherence',
  calm: 'technique.category.calm',
  stress: 'technique.category.stressRelief',
  sleep: 'technique.category.sleep',
  focus: 'technique.category.focusPerformance',
  energy: 'technique.category.energy',
  foundations: 'technique.category.foundations',
};
const categories = Object.entries(categoryKeys).map(([id, key]) => ({ id, title: localized(key) }));

const strings_ = {
  all: localized('breathe.filter.all'),
  inhale: localized('technique.inhale'),
  exhale: localized('technique.exhale'),
  hold: localized('technique.hold'),
  pause: localized('common.pause'),
  resume: localized('common.resume'),
  // Printf formats from the app, converted to {n}/{s} placeholders.
  cycle: mapValues(localized('session.cycle %lld'), (v) => v.replace('%lld', '{n}')),
  minutes: mapValues(localized('technique.durationMinutes %lld'), (v) => v.replace('%lld', '{n}')),
  phaseLabel: mapValues(localized('technique.phaseLabel %lld %@'), (v) => v.replace('%lld', '{n}').replace('%@', '{s}')),
};

function mapValues(object, fn) {
  return Object.fromEntries(Object.entries(object).map(([k, v]) => [k, fn(v)]));
}

const output = `// Generated by scripts/sync-app-content.mjs from the Breathia app repository
// (Shared/Domain/Model/TechniqueCatalog.swift and Shared/Localizable.xcstrings).
// Do not edit by hand — run \`npm run sync\` instead.

export const categories = ${JSON.stringify(categories, null, 2)};

export const techniques = ${JSON.stringify(techniques, null, 2)};

export const appStrings = ${JSON.stringify(strings_, null, 2)};
`;

await writeFile(path.join(root, 'content/app.js'), output);
console.log(`Synced ${techniques.length} techniques in ${categories.length} categories (${languages.join(', ')}).`);
